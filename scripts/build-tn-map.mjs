import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const geo = JSON.parse(fs.readFileSync(path.join(root, 'tamilnadu.geojson'), 'utf8'));

function slugify(name) {
  const map = {
    Kanyakumari: 'kanniyakumari',
    Thoothukkudi: 'thoothukudi',
    Thiruvallur: 'tiruvallur',
    Thiruvarur: 'tiruvarur',
    Tirupathur: 'tirupathur',
    Chengalpattu: 'chengalpattu',
    Kallakurichi: 'kallakurichi',
    Ranipet: 'ranipet',
    Tenkasi: 'tenkasi',
    Tiruppur: 'tiruppur',
  };
  const base = map[name] || name;
  return base
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

function displayName(name) {
  const map = {
    Kanyakumari: 'Kanniyakumari',
    Thoothukkudi: 'Thoothukudi',
    Thiruvallur: 'Tiruvallur',
    Thiruvarur: 'Tiruvarur',
    Sivaganga: 'Sivagangai',
  };
  return map[name] || name;
}

function flattenCoords(geom) {
  const rings = [];
  if (geom.type === 'Polygon') {
    for (const ring of geom.coordinates) rings.push(ring);
  } else if (geom.type === 'MultiPolygon') {
    for (const poly of geom.coordinates) {
      for (const ring of poly) rings.push(ring);
    }
  }
  return rings;
}

/** Keep shape readable — light simplify, drop tiny island fragments */
function simplify(ring, step = 3) {
  if (ring.length <= 12) return ring;
  const out = [];
  for (let i = 0; i < ring.length; i += step) out.push(ring[i]);
  const last = ring[ring.length - 1];
  const prev = out[out.length - 1];
  if (!prev || prev[0] !== last[0] || prev[1] !== last[1]) out.push(last);
  return out;
}

function ringArea(ring) {
  let a = 0;
  for (let i = 0; i < ring.length - 1; i += 1) {
    a += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
  }
  return Math.abs(a / 2);
}

function centroid(ring) {
  let a = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0; i < ring.length - 1; i += 1) {
    const cross = ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
    a += cross;
    cx += (ring[i][0] + ring[i + 1][0]) * cross;
    cy += (ring[i][1] + ring[i + 1][1]) * cross;
  }
  a *= 0.5;
  if (Math.abs(a) > 1e-12) return [cx / (6 * a), cy / (6 * a)];
  return [
    ring.reduce((s, p) => s + p[0], 0) / ring.length,
    ring.reduce((s, p) => s + p[1], 0) / ring.length,
  ];
}

let minX = Infinity;
let minY = Infinity;
let maxX = -Infinity;
let maxY = -Infinity;
const districts = [];

for (const f of geo.features) {
  const name = f.properties.district || f.properties.NAME_2;
  if (!name) continue;

  let rings = flattenCoords(f.geometry).map((r) => simplify(r, 3));

  // Drop tiny coastal fragments that make the map look broken
  const areas = rings.map(ringArea);
  const maxArea = Math.max(...areas);
  rings = rings.filter((ring, i) => areas[i] >= maxArea * 0.02 && areas[i] > 1e-6);

  if (!rings.length) continue;

  for (const ring of rings) {
    for (const [x, y] of ring) {
      if (x < minX) minX = x;
      if (y < minY) minY = y;
      if (x > maxX) maxX = x;
      if (y > maxY) maxY = y;
    }
  }

  let best = rings[0];
  let bestArea = 0;
  for (const ring of rings) {
    const a = ringArea(ring);
    if (a > bestArea) {
      bestArea = a;
      best = ring;
    }
  }

  const [cx, cy] = centroid(best);
  districts.push({ id: slugify(name), name: displayName(name), rings, cx, cy });
}

districts.sort((a, b) => a.name.localeCompare(b.name));

const pad = 14;
const width = 480;
const height = 620;
const spanX = maxX - minX;
const spanY = maxY - minY;
const scale = Math.min((width - pad * 2) / spanX, (height - pad * 2) / spanY);

function project([lng, lat]) {
  const x = pad + (lng - minX) * scale;
  const y = height - pad - (lat - minY) * scale;
  return [Number(x.toFixed(2)), Number(y.toFixed(2))];
}

const out = districts.map((d) => {
  const path = d.rings
    .map((ring) => {
      return (
        ring
          .map((pt, i) => {
            const [x, y] = project(pt);
            return `${i === 0 ? 'M' : 'L'}${x} ${y}`;
          })
          .join('') + 'Z'
      );
    })
    .join('');
  const [mx, my] = project([d.cx, d.cy]);
  return { id: d.id, name: d.name, path, label: { x: mx, y: my } };
});

const body = `/*
  Tamil Nadu district boundaries projected from open GeoJSON
  (udit-001/india-maps-data tamil-nadu.geojson — includes Krishnagiri and post-2019 districts).
  Generated by scripts/build-tn-map.mjs. Do not hand-edit paths.
*/

export const tamilNaduMap = {
  viewBox: '0 0 ${width} ${height}',
  width: ${width},
  height: ${height},
  attribution: 'District boundaries adapted from open Tamil Nadu GeoJSON.',
  districts: ${JSON.stringify(out, null, 2)},
};
`;

const dest = path.join(root, 'src', 'data', 'tamilNaduMap.js');
fs.writeFileSync(dest, body);
